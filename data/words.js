window.TEXTBOOK_WORDS = [];
function add(lesson, page, section, rows) {
  rows.trim().split('\n').forEach((row, i) => {
    const [ja, reading, zh, pos] = row.split('|');
    TEXTBOOK_WORDS.push({id: ['w', page, section, i + 1].join('-'), ja, reading: reading || ja.replace(/～/g, ''), zh, pos, lesson, page, section});
  });
}
